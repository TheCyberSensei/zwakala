'use strict';
const fs = require('node:fs');
const path = require('node:path');

function readSpec() {
  const markdown = fs.readFileSync(path.join(__dirname, 'form-spec.md'), 'utf8');
  const blocks = [...markdown.matchAll(/^```json\r?\n([\s\S]*?)^```\s*$/gm)];
  if (blocks.length !== 1) throw new Error('Expected exactly one JSON specification block.');
  return JSON.parse(blocks[0][1]);
}

function renderSpec(spec) {
  return '// Generated by build-spec.cjs from form-spec.md. Do not edit directly.\n' +
    'function getSurveySpec() {\n  return ' + JSON.stringify(spec, null, 2) + ';\n}\n';
}

if (require.main === module) {
  const args = process.argv.slice(2);
  if (args.some(arg => arg !== '--check') || args.length > 1) {
    throw new Error('Usage: node build-spec.cjs [--check]');
  }
  const target = path.join(__dirname, 'SurveySpec.gs');
  const expected = renderSpec(readSpec());
  if (args.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== expected) {
      throw new Error('SurveySpec.gs is missing or stale. Run npm run build and review the diff.');
    }
    console.log('PASS generated specification matches form-spec.md');
  } else {
    fs.writeFileSync(target, expected, 'utf8');
    console.log('Generated SurveySpec.gs');
  }
}
module.exports = { readSpec, renderSpec };
